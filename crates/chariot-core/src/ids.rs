use std::fmt;

use serde::{Deserialize, Serialize};

macro_rules! id_type {
    ($(#[$meta:meta])* $name:ident, generated) => {
        id_type!($(#[$meta])* $name);

        impl $name {
            /// Makes a fresh, time ordered identifier.
            pub(crate) fn generate() -> Self {
                Self(uuid::Uuid::now_v7().to_string())
            }
        }
    };
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
        #[serde(transparent)]
        pub struct $name(String);

        impl $name {
            /// Wraps an existing identifier string.
            pub fn new(id: impl Into<String>) -> Self {
                Self(id.into())
            }

            /// The identifier as a string slice.
            pub fn as_str(&self) -> &str {
                &self.0
            }
        }

        impl fmt::Display for $name {
            fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str(&self.0)
            }
        }

        impl From<&str> for $name {
            fn from(id: &str) -> Self {
                Self::new(id)
            }
        }

        impl AsRef<str> for $name {
            fn as_ref(&self) -> &str {
                &self.0
            }
        }
    };
}

id_type!(
    /// Identifies a member. Chosen by whoever enrols the member, for example
    /// `claude-code@max`, so it stays readable in logs.
    MemberId
);
id_type!(
    /// Identifies a task. Generated by the store.
    TaskId,
    generated
);
id_type!(
    /// Identifies an action in the action record. Generated by the store.
    ActionId,
    generated
);
id_type!(
    /// Identifies a hold. Generated by the store.
    HoldId,
    generated
);
